/**
 * Generates verify/vectors.json from the site's OWN encryption module.
 *
 * The vectors are produced by importing `src/cryptoPassword.js` directly — the
 * same file the browser runs — rather than by a reimplementation. A vector set
 * written by hand, or by a second implementation, would prove only that the two
 * agree with each other.
 *
 * Verification is by DECRYPTION, not re-encryption. AES-GCM uses a fresh random
 * IV per chunk, so re-encrypting the same plaintext never reproduces the same
 * bytes. Publishing ciphertext plus the expected plaintext hash is both
 * reproducible and a stronger check: it exercises the path a real user runs.
 *
 * Run: node scripts/gen-verify-vectors.mjs
 */

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { argon2id } from "hash-wasm";
import {
  ENCRYPTION_OVERHEAD,
  deriveKeyFromPassword,
  encodeBase64url,
  encryptChunkWithKey,
} from "../src/cryptoPassword.js";

/* Fixed inputs so the KDF vectors are byte-reproducible by anyone. */
const CASES = [
  { name: "ascii-password", password: "correct horse battery staple" },
  { name: "unicode-password", password: "pässwörd-🔐-日本語" },
  { name: "long-password", password: "x".repeat(200) },
];

/* Deterministic salt per case — real uploads use crypto.getRandomValues(). */
const saltFor = (index) => new Uint8Array(16).map((_, i) => (index * 31 + i * 7 + 3) % 256);

/* Small chunk size so a vector spans multiple chunks without a huge file.
   Production uses the server's MULTIPART_PART_SIZE_BYTES (10 MiB default). */
const VECTOR_CHUNK_SIZE = 64 * 1024;

function makePlaintext(bytes) {
  const out = Buffer.alloc(bytes);
  for (let i = 0; i < bytes; i += 1) out[i] = (i * 31 + 7) % 256;
  return out;
}

const vectors = [];

for (const [index, testCase] of CASES.entries()) {
  const salt = saltFor(index);

  /* The raw key, for a KDF-only check that needs no AES at all. The app's own
     deriveKeyFromPassword returns a non-extractable CryptoKey by design, so the
     raw bytes are derived separately here using identical parameters. */
  const rawKey = await argon2id({
    password: testCase.password,
    salt,
    parallelism: 1,
    iterations: 3,
    memorySize: 65536,
    hashLength: 32,
    outputType: "binary",
  });

  /* Deliberately not a multiple of the chunk size: the final short chunk is
     where reassembly maths goes wrong, so every vector must exercise it. */
  const plaintext = makePlaintext(VECTOR_CHUNK_SIZE * 2 + 1234);
  const key = await deriveKeyFromPassword(testCase.password, salt);

  const parts = [];
  for (let c = 0; c * VECTOR_CHUNK_SIZE < plaintext.length; c += 1) {
    const slice = plaintext.subarray(
      c * VECTOR_CHUNK_SIZE,
      Math.min((c + 1) * VECTOR_CHUNK_SIZE, plaintext.length),
    );
    const encrypted = await encryptChunkWithKey(
      key,
      slice.buffer.slice(slice.byteOffset, slice.byteOffset + slice.byteLength),
      c,
    );
    parts.push(Buffer.from(encrypted));
  }

  vectors.push({
    name: testCase.name,
    password: testCase.password,
    salt: encodeBase64url(salt),
    kdf: {
      algorithm: "argon2id",
      memoryKiB: 65536,
      iterations: 3,
      parallelism: 1,
      hashLength: 32,
      expectedKeyHex: Buffer.from(rawKey).toString("hex"),
    },
    cipher: {
      algorithm: "AES-256-GCM",
      chunkSize: VECTOR_CHUNK_SIZE,
      overheadPerChunk: ENCRYPTION_OVERHEAD,
      aad: "chunk-<0-based index>",
      plaintextSize: plaintext.length,
      expectedPlaintextSha256: createHash("sha256").update(plaintext).digest("hex"),
      ciphertextBase64: Buffer.concat(parts).toString("base64"),
    },
  });
}

const doc = {
  $comment:
    "Generated by scripts/gen-verify-vectors.mjs from src/cryptoPassword.js. " +
    "Verify by DECRYPTING ciphertextBase64 with the given password and salt, " +
    "then comparing the SHA-256 of the result to expectedPlaintextSha256. " +
    "Re-encrypting will NOT reproduce these bytes: the IV is random per chunk.",
  format: {
    perChunkLayout: "[ IV 12B ][ ciphertext ][ GCM tag 16B ]",
    chunksAreContiguous: true,
    aadTemplate: "chunk-${zeroBasedIndex}",
    saltEncoding: "base64url, no padding (RFC 4648 §5)",
    note: "plaintextSize is the PLAINTEXT length; chunk n is min(chunkSize, size - n*chunkSize) + 28 bytes on disk",
  },
  vectors,
};

const target = new URL("../verify/vectors.json", import.meta.url);
writeFileSync(target, `${JSON.stringify(doc, null, 2)}\n`);
console.log(`wrote ${vectors.length} vectors → verify/vectors.json`);
